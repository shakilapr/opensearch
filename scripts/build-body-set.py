#!/usr/bin/env python3
"""Build a second graded set whose queries come from document *bodies*, not titles.

Why: the existing 600-query set labels each document by its own title, which a lexical search
answers almost by construction (BM25 nDCG 0.4813 on 19K documents, 0.2481 on 1.5M). Any semantic
lane is therefore measured against a target it cannot paraphrase its way to. This set draws the
query from the body, so both lexical and semantic retrieval have to find a document from its
content rather than from its headline.

Construction, deterministic: documents ordered by resource_id, every Nth taken until 600, and from
each document's text the first sentence of 10-18 words that is not the title. No model is involved,
so the set can be regenerated byte-identically.
"""
import json
import re
import sqlite3
import sys

DB = "/var/lib/search/meta/meta.sqlite"
LIMIT = 600

c = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
rows = c.execute(
    """
    SELECT dv.resource_id, c.text_path, dv.title
      FROM document_version dv
      JOIN content c ON c.content_id = dv.content_id
     WHERE c.text_path IS NOT NULL
     ORDER BY dv.resource_id
    """
).fetchall()

step = max(1, len(rows) // (LIMIT * 3))
candidates = rows[::step]

WORD = re.compile(r"[A-Za-z][A-Za-z'\-]+")
out = []
for resource_id, path, title in candidates:
    if len(out) >= LIMIT:
        break
    try:
        text = open(path, encoding="utf-8", errors="replace").read()
    except OSError:
        continue
    title_words = set(w.lower() for w in WORD.findall(title or ""))
    for sentence in re.split(r"(?<=[.!?])\s+", text):
        words = WORD.findall(sentence)
        if not 10 <= len(words) <= 18:
            continue
        # Skip a sentence that is mostly the title repeated, or one made of very common words only.
        if title_words and len([w for w in words if w.lower() in title_words]) > len(words) // 3:
            continue
        if len({w.lower() for w in words}) < 8:
            continue
        out.append(
            {
                "id": f"body-{len(out):05d}",
                "query": " ".join(words),
                "class": "long_semantic",
                "relevant": [resource_id],
                "graded": [[resource_id, 3]],
                "observed_at": 1791600000,
            }
        )
        break

with open(sys.argv[1] if len(sys.argv) > 1 else "benchmarks/queries.body.jsonl", "w") as f:
    f.write("# Body-span query set: the query is a sentence from the document, the label is that\n")
    f.write("# document. Regenerate with scripts/build-body-set.py. NOT hand-judged.\n")
    for case in out:
        f.write(json.dumps(case) + "\n")
print(f"wrote {len(out)} cases from {len(candidates)} candidate documents")