//! Token accounting for the model calls made on the search path.
//!
//! A provider bills three numbers, and they are not interchangeable: `input` (prompt tokens sent),
//! `output` (completion tokens generated) and `cached` (input tokens the provider served from its
//! own prompt cache — usually far cheaper, and free on some tiers). Reporting them separately is
//! what makes a model change auditable: on a free tier it is also how you see rate-limit pressure,
//! and comparing `input` against `cached` shows whether the cache is actually being hit.

use serde::{Deserialize, Serialize};

/// Tokens consumed by one model call, or the sum of several.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct TokenUsage {
    /// Prompt tokens sent to the provider.
    pub input: u64,
    /// Completion tokens generated by the provider.
    pub output: u64,
    /// Input tokens the provider served from its prompt cache (a subset of `input`).
    pub cached: u64,
}

impl TokenUsage {
    /// `true` when nothing was billed — a cache hit, or a call that never reached a model.
    pub fn is_zero(&self) -> bool {
        self.input == 0 && self.output == 0 && self.cached == 0
    }

    /// Billable tokens: `input + output` (the cached share is part of `input`).
    pub fn total(&self) -> u64 {
        self.input + self.output
    }

    /// Accumulate another call's usage (saturating, so a runaway provider cannot wrap).
    pub fn add(&mut self, other: TokenUsage) {
        self.input = self.input.saturating_add(other.input);
        self.output = self.output.saturating_add(other.output);
        self.cached = self.cached.saturating_add(other.cached);
    }

    /// Read the usage out of an OpenAI-chat-compatible response body, tolerating the spelling
    /// differences between providers.
    ///
    /// `value` may be the whole response or the `usage` object itself. Providers disagree on where
    /// the cached count lives: OpenRouter and OpenAI use `prompt_tokens_details.cached_tokens`,
    /// Anthropic-style relays use `cache_read_input_tokens`, others a bare `cached_tokens`. Any
    /// missing field reads as zero rather than failing the call — usage is reporting, not contract.
    pub fn from_provider_json(value: &serde_json::Value) -> TokenUsage {
        let usage = value.get("usage").unwrap_or(value);
        let num = |v: &serde_json::Value, k: &str| v.get(k).and_then(|x| x.as_u64());

        let input = num(usage, "prompt_tokens").unwrap_or(0);
        let output = num(usage, "completion_tokens").unwrap_or(0);
        let cached = num(usage, "cached_tokens")
            .or_else(|| num(usage, "cache_read_input_tokens"))
            .or_else(|| {
                usage
                    .get("prompt_tokens_details")
                    .and_then(|d| num(d, "cached_tokens"))
            })
            .or_else(|| {
                usage
                    .get("input_tokens_details")
                    .and_then(|d| num(d, "cached_tokens"))
            })
            .unwrap_or(0);

        TokenUsage {
            input,
            output,
            cached,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_the_openai_openrouter_shape() {
        let body = serde_json::json!({
            "usage": {"prompt_tokens": 1200, "completion_tokens": 80, "total_tokens": 1280,
                       "prompt_tokens_details": {"cached_tokens": 900}}
        });
        let u = TokenUsage::from_provider_json(&body);
        assert_eq!(u, TokenUsage { input: 1200, output: 80, cached: 900 });
        assert_eq!(u.total(), 1280);
    }

    #[test]
    fn reads_the_anthropic_style_cached_field() {
        let body = serde_json::json!({
            "usage": {"prompt_tokens": 500, "completion_tokens": 20, "cache_read_input_tokens": 400}
        });
        assert_eq!(TokenUsage::from_provider_json(&body).cached, 400);
    }

    #[test]
    fn a_missing_usage_is_zero_not_an_error() {
        let body = serde_json::json!({"choices": [{"message": {"content": "hi"}}]});
        assert!(TokenUsage::from_provider_json(&body).is_zero());
    }

    #[test]
    fn accumulates_without_wrapping() {
        let mut total = TokenUsage::default();
        total.add(TokenUsage { input: 10, output: 2, cached: 3 });
        total.add(TokenUsage { input: u64::MAX, output: 1, cached: 0 });
        assert_eq!(total.input, u64::MAX);
        assert_eq!(total.output, 3);
        assert_eq!(total.cached, 3);
    }
}
